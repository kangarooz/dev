import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', headless: true });
const p = await (await b.newContext({ viewport:{width:1280,height:720} })).newPage();
import FixtureTarget from './lib/targets/fixture.mjs';
const t = new FixtureTarget({log(){}}); const origin = await t.start();
await p.goto(origin + '/workflow.html');
const top = () => p.evaluate(() => document.querySelector('.code').scrollTop);
console.log('start scrollTop            =', await top());
await p.mouse.wheel(0, 320); await p.waitForTimeout(300);
console.log('after mouse.wheel (as coded)=', await top(), '   <- mouse is at (0,0), over the 46px header');
await p.mouse.move(640, 400); await p.mouse.wheel(0, 320); await p.waitForTimeout(300);
console.log('after mouse.move + wheel    =', await top(), '   <- scrolls once the pointer is over .code');
await b.close(); await t.close();
